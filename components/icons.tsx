function doodle(viewWidth: number, viewHeight: number, strokeWidth: number, strokes: Stroke[]) {
  return function Doodle({ size = 24, ...props }: SVGProps<SVGSVGElement> & { size?: number }) {
    return (
      <svg
        xmlns="http://www.w3.org/2000/svg"
        viewBox={`0 0 ${viewWidth} ${viewHeight}`}
        width={(size * viewWidth) / viewHeight}
        height={size}
        fill="none"
        stroke="currentColor"
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden="true"
        {...props}
      >
        {strokes.map((stroke, i) => {
          const [d, width] = typeof stroke === "string" ? [stroke, strokeWidth] : stroke;
          return <path key={i} d={d} strokeWidth={width} />;
        })}
      </svg>
    );
  };
}

